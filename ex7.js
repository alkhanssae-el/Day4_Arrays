//In JavaScript, arrays are variables that have multiple items inside of them, its like a box that has multiple toys in it
//const prevents the reassignment of a variable, making it constant instead
const arr = [4, 5]
arr.push(3)
console.log(arr)
//Hence why this works, we didn't reassign the constant but instead only added an item
//While assigning arr = [4, 5] does not work, because it is impossible to reassign a constant